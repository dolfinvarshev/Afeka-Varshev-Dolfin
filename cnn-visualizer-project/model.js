var STORAGE_KEY = "cnn_corrected_v1";
function saveModelToStorage(obj) {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(obj));
    return { ok: true };
  } catch (e) {
    return {
      ok: false,
      message:
        "Error: Not enough space in localStorage. Please use a smaller exported model/remove data first.",
    };
  }
}
function loadModelFromStorage() {
  try {
    var s = localStorage.getItem(STORAGE_KEY);
    return s ? JSON.parse(s) : null;
  } catch (e) {
    return null;
  }
}
